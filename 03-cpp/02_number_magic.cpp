#include <iostream>
using namespace std;

int main() {
    int a = 8;
    int b = 3;

    cout << "a = " << a << endl;
    cout << "b = " << b << endl;
    cout << "a + b = " << a + b << endl;
    cout << "a - b = " << a - b << endl;
    cout << "a * b = " << a * b << endl;
    cout << "a / b = " << a / b << "，这是整数除法，小数被吃掉了。" << endl;

    return 0;
}
